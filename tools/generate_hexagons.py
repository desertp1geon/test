#!/usr/bin/env python3
"""
Generates the Flyway seed migration with H3 cells covering Ukraine.

Source of boundaries: Natural Earth 1:10m Admin-1 (public domain),
https://github.com/nvkelso/natural-earth-vector
Regions are selected by ISO 3166-2 code (UA-*), i.e. internationally
recognised borders (Crimea UA-43 and Sevastopol UA-40 included).

A cell belongs to a region if its centre lies inside the region polygon.

Usage:
  python3 generate_hexagons.py --geojson ne_10m_admin_1_states_provinces.geojson \
      --resolution 5 --out ../app/src/main/resources/db/migration/V2__seed_hexagons.sql
Requires: pip install h3 shapely   (h3 >= 4)
"""
import argparse, json
import h3
from shapely.geometry import shape, mapping, Point

ap = argparse.ArgumentParser()
ap.add_argument("--geojson", required=True)
ap.add_argument("--resolution", type=int, default=5)
ap.add_argument("--out", required=True)
a = ap.parse_args()

data = json.load(open(a.geojson, encoding="utf-8"))
regions = []
for f in data["features"]:
    p = f["properties"]
    if (p.get("iso_3166_2") or "").startswith("UA-"):
        regions.append((p["iso_3166_2"], p["name_uk"], shape(f["geometry"])))

# Kyiv has two features (UA-30 city, UA-32 listed as "Київ" in NE = Kyiv Oblast).
names = {"UA-32": "Київська область", "UA-30": "місто Київ", "UA-40": "місто Севастополь"}

cells = {}  # h3 -> region
for code, name_uk, geom in regions:
    name = names.get(code, name_uk)
    polys = geom.geoms if geom.geom_type == "MultiPolygon" else [geom]
    found = set()
    for poly in polys:
        gj = mapping(poly)
        found |= set(h3.geo_to_cells(gj, a.resolution))
    if not found:  # tiny region: use the cell under a representative point
        pt = geom.representative_point()
        found = {h3.latlng_to_cell(pt.y, pt.x, a.resolution)}
    for c in found:
        cells.setdefault(c, (code, name))

idx = set(cells)
def q(s): return "'" + s.replace("'", "''") + "'"

rows, pairs = [], []
for c, (code, name) in sorted(cells.items()):
    lat, lng = h3.cell_to_latlng(c)
    b = [[round(la, 4), round(ln, 4)] for la, ln in h3.cell_to_boundary(c)]
    rows.append(f"({q(c)},{lat:.5f},{lng:.5f},{q(name)},{q(code)},'{json.dumps(b,separators=(',',':'))}')")
    for n in h3.grid_ring(c, 1):
        if n in idx and n != c:
            pairs.append(f"({q(c)},{q(n)})")

with open(a.out, "w", encoding="utf-8") as o:
    o.write(f"-- GENERATED by tools/generate_hexagons.py (H3 resolution {a.resolution}). Do not edit.\n")
    o.write("-- Boundaries: Natural Earth 1:10m Admin-1, public domain.\n\n")
    o.write("INSERT INTO hexagons (h3_index, resolution, center_lat, center_lng, name, region_name, region_code, boundary)\n")
    o.write(f"SELECT v.h3, {a.resolution}, v.lat, v.lng, v.region, v.region, v.code, v.b::jsonb FROM (VALUES\n")
    o.write(",\n".join(rows) + "\n) AS v(h3, lat, lng, region, code, b);\n\n")
    o.write("INSERT INTO hexagon_neighbours (hexagon_id, neighbour_hexagon_id)\n")
    o.write("SELECT h1.id, h2.id FROM (VALUES\n")
    o.write(",\n".join(pairs) + "\n) AS p(a, b)\nJOIN hexagons h1 ON h1.h3_index = p.a\nJOIN hexagons h2 ON h2.h3_index = p.b;\n")

from collections import Counter
cnt = Counter(v[1] for v in cells.values())
print("cells:", len(cells), "neighbour pairs:", len(pairs))
for k, v in sorted(cnt.items(), key=lambda x: -x[1]): print(f"  {v:4d} {k}")
print("regions without cells:", [c for c, n, _ in regions if names.get(c, n) not in cnt])
